/*
 * sync_to_project.js —— 把渲染产物同步进小程序工程
 *
 * 关键改动：**剔除死字段**
 *   latex / blankLatex / grade 在页面与组件里引用次数为 0
 *   （公式已预渲染成图，LaTeX 源码运行时用不到），
 *   剔除后 data/formulas.js 体积下降约 72KB，为主包腾出空间。
 *
 * 用法: node sync_to_project.js
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const SRC = path.join(ROOT, 'extract/build/formulas.js')
const DST = path.join(ROOT, '新建文件夹/data/formulas.js')

const DEAD_FIELDS = ['latex', 'blankLatex', 'grade']

const mod = require(SRC)
const { FORMULAS, CHAPTERS, CHAPTER_COUNTS } = mod

const before = fs.statSync(SRC).size

const slim = FORMULAS.map(item => {
  const out = {}
  for (const [k, v] of Object.entries(item)) {
    if (DEAD_FIELDS.includes(k)) continue
    out[k] = v
  }
  return out
})

// 校验：剔除后不能少掉页面用到的字段
const REQUIRED = ['id', 'chapter', 'name', 'condition', 'pitfall', 'example', 'voiceText',
  'tags', 'type', 'typeLabel', 'blankAnswer', 'formulaImage', 'formulaWidth', 'formulaHeight',
  'blankImage', 'blankWidth', 'blankHeight', 'exampleImage', 'exampleWidth', 'exampleHeight']
const missing = REQUIRED.filter(k => !(k in slim[0]))
if (missing.length) throw new Error('剔除过度，缺少必需字段: ' + missing.join(', '))

const content = `// Generated by extract/sync_to_project.js (源: extract/build/formulas.js). Do not edit manually.
const FORMULAS = ${JSON.stringify(slim)};

const CHAPTERS = ${JSON.stringify(CHAPTERS)};

const CHAPTER_COUNTS = ${JSON.stringify(CHAPTER_COUNTS)};

module.exports = {
  FORMULAS,
  CHAPTERS,
  CHAPTER_COUNTS
};
`

fs.mkdirSync(path.dirname(DST), { recursive: true })
fs.writeFileSync(DST, content, 'utf8')

const after = fs.statSync(DST).size
console.log(JSON.stringify({
  items: slim.length,
  deadFieldsRemoved: DEAD_FIELDS,
  sourceBytes: before,
  writtenBytes: after,
  savedKB: Number(((before - after) / 1024).toFixed(1)),
  dst: DST
}, null, 2))
