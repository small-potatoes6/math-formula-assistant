/*
 * build_svg_subpackages.js
 *
 * 把公式 SVG 按章节均衡分配到三个普通分包，并重写小程序数据中的资源路径。
 * 源文件始终来自 extract/build/formulas，目标目录和 data/formulas.js 都可重复生成。
 * 构建时校验 SVG 宽高比例与逻辑尺寸一致，防止旧资源被误打包后拉伸模糊。
 *
 * 用法:
 *   node extract/build_svg_subpackages.js
 */
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const PROJECT = path.join(ROOT, '新建文件夹')
const DATA_FILE = path.join(PROJECT, 'data/formulas.js')
const SOURCE_DATA_FILE = path.join(ROOT, 'extract/build/formulas.js')
const SOURCE_ASSET_DIR = path.join(ROOT, 'extract/build/formulas')

const PACKAGES = [
  {
    root: 'formula-package-a',
    name: 'formulaA',
    chapters: [
      '圆锥曲线的方程',
      '导数',
      '空间向量与立体几何',
      '解三角形',
      '集合与常用逻辑用语'
    ]
  },
  {
    root: 'formula-package-b',
    name: 'formulaB',
    chapters: [
      '函数的概念与性质',
      '平面向量及其应用',
      '立体几何初步',
      '概率与统计',
      '排列组合与二项式定理',
      '复数'
    ]
  },
  {
    root: 'formula-package-c',
    name: 'formulaC',
    chapters: [
      '三角函数',
      '数列',
      '直线与圆的方程',
      '一元二次函数、方程和不等式',
      '随机变量及其分布列'
    ]
  }
]

const ASSET_FIELDS = [
  ['formulaImage', 'formulaWidth', 'formulaHeight'],
  ['blankImage', 'blankWidth', 'blankHeight'],
  ['exampleImage', 'exampleWidth', 'exampleHeight']
]

function assertInside(parent, child, label) {
  const parentPath = path.resolve(parent)
  const childPath = path.resolve(child)
  const relative = path.relative(parentPath, childPath)
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(`${label} 路径越界: ${childPath}`)
  }
}

function cleanGeneratedDirectory(dir) {
  assertInside(PROJECT, dir, '清理目录')
  fs.rmSync(dir, { recursive: true, force: true })
  fs.mkdirSync(dir, { recursive: true })
}

function formatMB(bytes) {
  return Number((bytes / 1024 / 1024).toFixed(3))
}

function assertAssetMatchesDimensions(file, item, widthField, heightField) {
  const source = fs.readFileSync(file, 'utf8')
  const match = source.match(/<svg[^>]*\swidth="([0-9]+)"\s+height="([0-9]+)"/)
  if (!match) {
    throw new Error(`${item.id} 的 SVG 缺少有效宽高: ${file}`)
  }

  const svgWidth = Number(match[1])
  const svgHeight = Number(match[2])
  const logicalWidth = Number(item[widthField])
  const logicalHeight = Number(item[heightField])
  if (!logicalWidth || !logicalHeight) {
    throw new Error(`${item.id} 的逻辑尺寸缺失: ${logicalWidth}x${logicalHeight}`)
  }

  const scaleX = svgWidth / logicalWidth
  const scaleY = svgHeight / logicalHeight
  if (Math.abs(scaleX - scaleY) > 0.01) {
    throw new Error(
      `${item.id} 的资源尺寸与数据比例不一致: ` +
      `SVG ${svgWidth}x${svgHeight}, data ${logicalWidth}x${logicalHeight}`
    )
  }
}

const { FORMULAS, CHAPTERS, CHAPTER_COUNTS } = require(SOURCE_DATA_FILE)

const chapterToPackage = new Map()
for (const pkg of PACKAGES) {
  for (const chapter of pkg.chapters) {
    if (chapterToPackage.has(chapter)) {
      throw new Error(`章节重复分组: ${chapter}`)
    }
    chapterToPackage.set(chapter, pkg)
  }
}

const missingChapters = CHAPTERS.filter(chapter => !chapterToPackage.has(chapter))
const unknownChapters = Array.from(chapterToPackage.keys()).filter(chapter => !CHAPTERS.includes(chapter))
if (missingChapters.length || unknownChapters.length) {
  throw new Error(`章节分组不完整，缺少: ${missingChapters.join(', ') || '无'}；多余: ${unknownChapters.join(', ') || '无'}`)
}

const packageStats = new Map(PACKAGES.map(pkg => [pkg.root, {
  root: pkg.root,
  name: pkg.name,
  chapters: pkg.chapters,
  items: 0,
  files: new Set(),
  bytes: 0
}]))

for (const pkg of PACKAGES) {
  const assetDir = path.join(PROJECT, pkg.root, 'assets/formulas')
  cleanGeneratedDirectory(assetDir)
}

const rewritten = FORMULAS.map(item => {
  const pkg = chapterToPackage.get(item.chapter)
  if (!pkg) throw new Error(`${item.id} 的章节没有分包: ${item.chapter}`)

  const stats = packageStats.get(pkg.root)
  stats.items += 1

  const out = { ...item }
  for (const [assetField, widthField, heightField] of ASSET_FIELDS) {
    const asset = item[assetField]
    if (!asset) continue

    const filename = path.basename(asset)
    const sourceFile = path.join(SOURCE_ASSET_DIR, filename)
    const targetDir = path.join(PROJECT, pkg.root, 'assets/formulas')
    const targetFile = path.join(targetDir, filename)

    if (!fs.existsSync(sourceFile)) {
      throw new Error(`${item.id} 缺少资源: ${sourceFile}`)
    }
    assertAssetMatchesDimensions(sourceFile, item, widthField, heightField)

    assertInside(PROJECT, targetFile, '目标资源')
    if (!stats.files.has(filename)) {
      fs.copyFileSync(sourceFile, targetFile)
      stats.files.add(filename)
      stats.bytes += fs.statSync(targetFile).size
    }

    out[assetField] = `/${pkg.root}/assets/formulas/${filename}`
  }
  return out
})

const content = `// Generated by extract/build_svg_subpackages.js. Do not edit manually.
const FORMULAS = ${JSON.stringify(rewritten)};

const CHAPTERS = ${JSON.stringify(CHAPTERS)};

const CHAPTER_COUNTS = ${JSON.stringify(CHAPTER_COUNTS)};

module.exports = {
  FORMULAS,
  CHAPTERS,
  CHAPTER_COUNTS
};
`

fs.writeFileSync(DATA_FILE, content, 'utf8')

const report = PACKAGES.map(pkg => {
  const stats = packageStats.get(pkg.root)
  return {
    root: pkg.root,
    name: pkg.name,
    chapters: pkg.chapters.length,
    items: stats.items,
    files: stats.files.size,
    sizeMB: formatMB(stats.bytes)
  }
})

console.log(JSON.stringify({
  totalItems: rewritten.length,
  totalFiles: report.reduce((sum, item) => sum + item.files, 0),
  totalSizeMB: Number(report.reduce((sum, item) => sum + item.sizeMB, 0).toFixed(3)),
  packages: report
}, null, 2))
